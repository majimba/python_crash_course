# This program demonstrates basic arithmetic operations in Python
# Each operation will output the number 8 in different ways

# Addition: Adding two numbers using the + operator
# 3 + 5 evaluates to 8
print(3 + 5)  # Output: 8

# Subtraction: Subtracting one number from another using the - operator
# 10 - 2 evaluates to 8
print(10 - 2)  # Output: 8

# Multiplication: Multiplying two numbers using the * operator
# 2 * 4 evaluates to 8
print(2 * 4)  # Output: 8

# Division: Dividing one number by another using the / operator
# 40 / 5 evaluates to 8.0 (note: division always returns a float in Python 3)
print(40 / 5)  # Output: 8.0