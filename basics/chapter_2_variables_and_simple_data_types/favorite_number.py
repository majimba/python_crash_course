# This program demonstrates the use of variables and f-strings in Python

# Store favorite number in a variable
# Variables can store any type of data (numbers, strings, etc.)
# Here we store an integer (whole number)
num = 8

# Use an f-string to create a formatted message
# f-strings (formatted string literals) let you embed expressions inside string literals
# The {num} syntax inside the f-string will be replaced with the value of num
# f-strings were introduced in Python 3.6 and are the preferred way to format strings
print(f"My favorite number is {num}!")  # Output: My favorite number is 8!