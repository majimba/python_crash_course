# Demonstrating variable reassignment
# Variables in Python can be reassigned to new values at any time
# This is why they're called variables - their values can vary

# Initial value assignment
message = "I love coding in Python!"  # First message
print(message)  # Display first message

# Changing the value of the variable
message = "I cant wait to solve real world problems with python"  # New message
print(message)  # Display new message

# Note: The original message is lost after reassignment
# Each variable can only hold one value at a time
